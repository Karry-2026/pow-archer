def sheet(wb, name, tab, title, sub, heads, widths):
    ws = wb.create_sheet(name)
    ws.sheet_properties.tabColor = tab
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(heads))
    c = ws.cell(1, 1, title)
    c.font = TITLE_FONT
    c.alignment = LEFT
    ws.row_dimensions[1].height = 30

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=len(heads))
    c2 = ws.cell(2, 1, sub)
    c2.font = SUB_FONT
    c2.alignment = LEFT
    ws.row_dimensions[2].height = 30

    r = 3
    for i, h in enumerate(heads, 1):
        c = ws.cell(r, i, h)
        c.fill = HEAD_BG; c.font = HEAD_FG
        c.alignment = CEN; c.border = BORDER
    ws.row_dimensions[r].height = 26
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = 'A4'
    return ws, 4


def row(ws, r, vals, kinds=None):
    """kinds: 'i' 可改 / 'r' 只读 / 't' 文本 / 'b' 加粗"""
    for i, v in enumerate(vals, 1):
        c = ws.cell(r, i, v)
        k = (kinds[i-1] if kinds and i-1 < len(kinds) else 't')
        if k == 'i':
            c.fill = INPUT_BG; c.font = INPUT_FG
        elif k == 'r':
            c.fill = REF_BG; c.font = REF_FG
        elif k == 'b':
            c.font = BOLD
        else:
            c.font = TXT_FG
        c.border = BORDER
        c.alignment = CEN if i > 1 else LEFT
    ws.row_dimensions[r].height = 21


